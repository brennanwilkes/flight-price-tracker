#!/usr/bin/env node
/* Builds frontend/app/land.js: coastlines for the trip map, from Natural Earth 1:50m land
 * (public domain) as packaged by world-atlas. Run by hand when the region changes:
 *
 *   curl -sfLo /tmp/land-50m.json https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-50m.json
 *   node scripts/build-land.mjs /tmp/land-50m.json
 *
 * Decodes the TopoJSON, clips every ring to REGION, and rounds to STEP degrees (under a pixel
 * at the map's largest zoom). Rings are stored as flat integer arrays in STEP units.
 */
import fs from 'node:fs';

const REGION = { w: 90, e: 152, s: -10, n: 48 }; // every destination, plus the way out to the NE
const STEP = 0.05;
const MIN_POINTS = 4; // drop islets that round away

const [input] = process.argv.slice(2);
if (!input) throw new Error('usage: node scripts/build-land.mjs <land-50m.json>');
const topo = JSON.parse(fs.readFileSync(input, 'utf8'));
const { scale: [kx, ky], translate: [tx, ty] } = topo.transform;

// TopoJSON arcs are quantized and delta-encoded; a negative index means the arc reversed.
const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * kx + tx, y * ky + ty]; });
});
const ring = (ids) => ids.flatMap((i, n) => {
  const pts = i < 0 ? [...arcs[~i]].reverse() : arcs[i];
  return n === 0 ? pts : pts.slice(1);
});

const geoms = topo.objects.land.type === 'GeometryCollection' ? topo.objects.land.geometries : [topo.objects.land];
const rings = [];
for (const g of geoms) {
  const polys = g.type === 'Polygon' ? [g.arcs] : g.type === 'MultiPolygon' ? g.arcs : [];
  for (const p of polys) for (const r of p) rings.push(ring(r));
}

// Sutherland–Hodgman against each edge of the region.
function clip(pts) {
  const edges = [
    [(p) => p[0] >= REGION.w, (a, b) => at(a, b, 0, REGION.w)],
    [(p) => p[0] <= REGION.e, (a, b) => at(a, b, 0, REGION.e)],
    [(p) => p[1] >= REGION.s, (a, b) => at(a, b, 1, REGION.s)],
    [(p) => p[1] <= REGION.n, (a, b) => at(a, b, 1, REGION.n)],
  ];
  for (const [inside, cross] of edges) {
    const out = [];
    for (let i = 0; i < pts.length; i++) {
      const cur = pts[i], prev = pts[(i + pts.length - 1) % pts.length];
      if (inside(cur)) {
        if (!inside(prev)) out.push(cross(prev, cur));
        out.push(cur);
      } else if (inside(prev)) out.push(cross(prev, cur));
    }
    pts = out;
    if (!pts.length) break;
  }
  return pts;
}
function at(a, b, axis, v) {
  const t = (v - a[axis]) / (b[axis] - a[axis]);
  return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
}

const out = [];
for (const r of rings) {
  const flat = [];
  let px, py;
  for (const [x, y] of clip(r)) {
    const qx = Math.round(x / STEP), qy = Math.round(y / STEP);
    if (qx === px && qy === py) continue;
    flat.push(qx, qy);
    px = qx; py = qy;
  }
  if (flat.length >= MIN_POINTS * 2) out.push(flat);
}

const body = `// Generated by scripts/build-land.mjs from Natural Earth 1:50m land (public domain). Do not edit.
// Rings of [lon, lat, lon, lat, …] in units of STEP degrees, clipped to the map region.
export const STEP = ${STEP};
export const LAND = ${JSON.stringify(out)};
`;
fs.writeFileSync(new URL('../frontend/app/land.js', import.meta.url), body);
console.log(`land.js: ${out.length} rings, ${out.reduce((n, r) => n + r.length / 2, 0)} points, ${(body.length / 1024).toFixed(0)} KB`);
